/**
 * Автоматический захват стрелка: по нам открыли огонь — берём его в прицел сами.
 *
 * Два правила, и второе важнее первого. Свой выбор игрока мы не трогаем никогда: наводимся только тогда,
 * когда прицел свободен. А если игрок снял или сменил именно нашу, автоматическую цель — значит, он не хочет
 * её видеть, и следующие несколько секунд мы молчим. Без паузы снятая цель возвращалась бы следующим же
 * выстрелом по нам, и снять её было бы невозможно, пока по тебе стреляют.
 */

/** Столько не наводимся сами после того, как игрок отменил наш выбор. */
export const AUTO_TARGET_PAUSE_MS = 5000;

export class AutoTarget {
  /** Текущая цель выбрана нами, а не игроком. */
  private auto = false;

  /** До этого момента не наводимся; 0 — можно. */
  private pauseUntil = 0;

  constructor(private readonly pauseMs = AUTO_TARGET_PAUSE_MS) {}

  /**
   * Цель сменилась. Зовётся на каждую смену, чей бы выбор это ни был.
   * @param auto выбор наш, а не игрока
   */
  changed(auto: boolean, now: number): void {
    // Игрок переиграл нас — пауза. Смена одной нашей цели на другую нашу паузы не даёт.
    if (!auto && this.auto) this.pauseUntil = now + this.pauseMs;
    this.auto = auto;
  }

  /** Можно ли сейчас навестись самим. */
  allows(now: number): boolean {
    return now >= this.pauseUntil;
  }

  /** Сколько миллисекунд ещё молчим; 0 — не молчим. Для подсказок и тестов. */
  pausedFor(now: number): number {
    return Math.max(0, this.pauseUntil - now);
  }

  /** Цель, которая сейчас стоит, выбрана нами. */
  get isAuto(): boolean {
    return this.auto;
  }
}
