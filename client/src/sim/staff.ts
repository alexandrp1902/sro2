/**
 * Люди дока: у каждого места свои диспетчер, торговец, мастер верфи и мастер ангара — с именем,
 * фамилией и своей манерой здороваться. Никто их не хранит: всё выводится из ключей, поэтому
 * состав не меняется от визита к визиту.
 *
 * Имя обязано совпадать с картинкой (public/dock/*-office|trader.webp): там нарисованы конкретные
 * люди, и полинезийца с татуировками нельзя звать Олегом Громовым. Поэтому у каждой картинки в
 * APPEARANCE прописаны пол и происхождение — оттуда пул имён, а само имя своё у каждого места.
 * Пока несколько доков делят один портрет (пачка L в art/next-art-requests.md заказывает каждому
 * свой), там живут разные люди одного типа: две скандинавки в парках, но с разными именами. Когда
 * у места появится своя картинка, у него сменится ключ сцены — и имя пересчитается под неё.
 * Верфь и ангар нарисованы сверху, без людей, — там имя свободное. Торговец джунглей — ящер:
 * у него одно имя, фамилий у его народа не водится.
 *
 * Реплики написаны без рода говорящего («говорят», а не «слышал»): одна строка годится всем.
 */

export type StaffRole = 'missions' | 'cargo' | 'hulls' | 'ships';

export interface StaffMember {
  /** «Имя Фамилия»; у ящера — одно имя. */
  name: string;
  /** Должность маленькими буквами: «диспетчер». */
  role: string;
  /** Приветствие — своё у каждого и не меняется от визита к визиту. */
  line: string;
}

/**
 * Строка → число, одинаково в любом браузере и между запусками. Перемешивание на каждом символе нужно
 * всерьёз: у простого FNV младшие биты похожих строк («st:sol|cargo», «st:vega|cargo») совпадали,
 * и остаток от деления давал всем местам одного и того же человека.
 */
export function hash(text: string): number {
  let h = 0x9e3779b9;
  for (let i = 0; i < text.length; i++) {
    h = Math.imul(h ^ text.charCodeAt(i), 0x5bd1e995);
    h ^= h >>> 15;
  }
  h = Math.imul(h ^ (h >>> 16), 0x85ebca6b);
  h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
  h ^= h >>> 16;
  return h >>> 0;
}

/** Элемент списка по строке-зерну: одно зерно — всегда один и тот же выбор. */
export function pick<T>(list: readonly T[], seed: string): T {
  return list[hash(seed) % list.length];
}

/**
 * Пул имён одного происхождения. Фамилии — парами «он / она»: у славянских и степных женская форма
 * своя (Мельников → Мельникова), у остальных фамилия по-русски не меняется (Картер, Танака — для обоих).
 */
interface NamePool {
  m: readonly string[];
  f: readonly string[];
  last: readonly (readonly [string, string])[];
}

/** Обе формы одинаковы: несклоняемая фамилия. */
function inv(names: readonly string[]): (readonly [string, string])[] {
  return names.map((n) => [n, n] as const);
}

