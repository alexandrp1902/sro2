namespace Sro.Server.Game;

/// <summary>
/// Корабль NPC, который подбирает груз в космосе (GDD §21, §31). Раньше так умели только пираты; рейнджеры
/// и торговцы пролетали мимо брошенного добра, и оно висело в пустоте до истечения срока.
///
/// Трюм тут настоящий: подобранное считается по объёму, видно всем лучом подбора и высыпается, если корабль
/// собьют, — ограбить сборщика можно так же, как пирата.
/// </summary>
public interface IScavenger
{
    /// <summary>Что уже подобрано.</summary>
    Cargo Hold { get; }

    /// <summary>Груз, к которому корабль сейчас летит; 0 — ни к какому.</summary>
    int LootId { get; set; }

    /// <summary>Где этот груз: курс на него держит ИИ, а система лута только отдаёт его в трюм.</summary>
    double LootX { get; set; }
    double LootY { get; set; }
}
